#!/usr/bin/env python3
"""Build page-only data from the canonical UI catalog and translations.

The catalog keeps validation, CSS and built-in preset data. Categories, groups,
descriptions and controller annotations belong to the settings UI only.
Translations cover every manifest content script and worker dependency, because
worker errors can reach page dialogs. Catalog labels also reach dynamic errors.
Substring selection is deliberately conservative: unused matches cost bytes,
whereas narrowing this to t('literal') would lose worker and dynamic messages.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "extension"
DATA_FILES = {"catalog.js", "locales.js", "runtime-catalog.js", "runtime-locales.js"}
OPTION_FIELDS = ("id", "category", "type", "default", "choices", "label", "css", "implementation")


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def canonical_data():
    catalog_text = (SOURCE / "catalog.js").read_text()
    catalog = json.loads(catalog_text.split("globalThis.YTV_CATALOG = ", 1)[1].strip().removesuffix(";"))
    locales_text = (SOURCE / "locales.js").read_text()
    messages = json.loads(locales_text.split("Object.freeze({ru: Object.freeze(", 1)[1].rsplit(")", 2)[0])
    return catalog, messages


def runtime_sources():
    manifest = json.loads((SOURCE / "manifest.json").read_text())
    pending = {name for entry in manifest["content_scripts"] for name in entry["js"]}
    pending.add(manifest["background"]["service_worker"])
    sources = {}
    while pending:
        name = min(pending)
        pending.remove(name)
        if name in DATA_FILES or name in sources:
            continue
        text = (SOURCE / name).read_text()
        sources[name] = text
        # This extension uses static importScripts calls. Include all dependencies,
        # even those used by settings-only actions, to keep remote errors intact.
        for call in re.findall(r"\bimportScripts\s*\(([^)]*)\)", text):
            pending.update(re.findall(r"['\"]([^'\"]+\.js)['\"]", call))
    return sources


def generated_files():
    catalog, messages = canonical_data()
    runtime_catalog = {
        "options": [{key: option[key] for key in OPTION_FIELDS if key in option} for option in catalog["options"]],
        "presets": catalog["presets"],
    }
    # Include single/double quoted escaped forms as well as literal template/HTML
    # text. Every canonical key is considered, rather than parsing only t() calls.
    text = "\n".join(runtime_sources().values())
    labels = {option["label"] for option in catalog["options"]}
    labels.update(preset["label"] for preset in catalog["presets"])
    selected = set(labels)
    for message in messages:
        escaped = json.dumps(message, ensure_ascii=False)[1:-1]
        single_quoted = message.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r")
        if any(form in text for form in (message, escaped, single_quoted)):
            selected.add(message)
    # i18n.source() builds a reverse map whose last translation wins. Preserve
    # collisions and their canonical order so switching RU back to EN is exact.
    translated = {messages[key] for key in selected if key in messages}
    runtime_messages = {key: value for key, value in messages.items() if key in selected or value in translated}
    header = "/* Generated by scripts/build-runtime.py; edit canonical data, then rebuild. */\n"
    return {
        "runtime-catalog.js": header + "globalThis.YTV_CATALOG=" + compact(runtime_catalog) + ";\n",
        "runtime-locales.js": header + "globalThis.YFE_LOCALES=Object.freeze({ru:Object.freeze(" + compact(runtime_messages) + ")});\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in runtime data is stale")
    args = parser.parse_args()
    stale = []
    for name, content in generated_files().items():
        path = SOURCE / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                stale.append(name)
        else:
            path.write_bytes(content.encode("utf-8"))
    if stale:
        parser.exit(1, "Stale runtime data: " + ", ".join(stale) + ". Run python3 scripts/build-runtime.py\n")


if __name__ == "__main__":
    main()
